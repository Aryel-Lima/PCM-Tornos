-- Atualização automática do campo updated_at nas tabelas mutáveis.
DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY['roles','users','equipment','equipment_documents','operating_records','performance_indicators','failures','preventive_plans','preventive_tasks','inventory_items','suppliers','supplier_quotes','work_orders','work_order_items','inventory_movements','maintenance_costs'] LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS trg_%I_updated_at ON %I', t, t);
    EXECUTE format('CREATE TRIGGER trg_%I_updated_at BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION set_updated_at()', t, t);
  END LOOP;
END $$;

-- Indicadores calculados são expostos por views para evitar duplicar resultados derivados.
-- Os valores medidos permanecem rastreáveis ao registro operacional de origem.
CREATE OR REPLACE VIEW v_performance_indicators_trace AS
SELECT pi.id AS indicator_id, pi.equipment_id, e.code AS equipment_code, e.name AS equipment_name,
       pi.indicator_code, pi.measured_at, pi.value, pi.unit, pi.target_value,
       pi.operating_record_id, orc.recorded_at AS source_recorded_at,
       orc.source_type AS source_record_type, orc.source_reference,
       pi.source_type AS indicator_source_type, pi.source_reference AS indicator_source_reference
FROM performance_indicators pi
JOIN equipment e ON e.id = pi.equipment_id
LEFT JOIN operating_records orc ON orc.id = pi.operating_record_id;

CREATE OR REPLACE VIEW v_inventory_balances AS
SELECT i.id AS inventory_item_id, i.code, i.name, i.unit, i.minimum_quantity, i.active,
       COALESCE(SUM(CASE WHEN m.movement_type IN ('entrada','ajuste_entrada','estorno_entrada') THEN m.quantity
                         WHEN m.movement_type IN ('saida','ajuste_saida','estorno_saida') THEN -m.quantity ELSE 0 END), 0) AS quantity_on_hand,
       COALESCE(SUM(CASE WHEN m.movement_type IN ('entrada','ajuste_entrada','estorno_entrada') THEN m.quantity * COALESCE(m.unit_cost, i.unit_cost)
                         WHEN m.movement_type IN ('saida','ajuste_saida','estorno_saida') THEN -m.quantity * COALESCE(m.unit_cost, i.unit_cost) ELSE 0 END), 0) AS inventory_value
FROM inventory_items i LEFT JOIN inventory_movements m ON m.inventory_item_id = i.id
GROUP BY i.id, i.code, i.name, i.unit, i.minimum_quantity, i.active;

CREATE OR REPLACE VIEW v_inventory_reorder_alerts AS
SELECT * FROM v_inventory_balances WHERE active = true AND quantity_on_hand <= minimum_quantity;

CREATE OR REPLACE VIEW v_maintenance_cost_totals AS
SELECT mc.id, mc.equipment_id, mc.work_order_id, mc.cost_type, mc.description,
       mc.quantity, mc.unit_cost, (mc.quantity * mc.unit_cost) AS total_cost,
       mc.incurred_at, mc.supplier_id
FROM maintenance_costs mc;

